"""
FastAPI Backend for Embeddable PLM Intelligence Chat Widget.
Module: api.py
"""

import os
from typing import Optional
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import google.generativeai as genai
from plm_logic import get_engine

# -------------------------------------------------------------
# 1. FastAPI App Initialization & CORS Configuration
# -------------------------------------------------------------
app = FastAPI(
    title="PLM Intelligence Chatbot API",
    description="REST API for querying 3DEXPERIENCE PLM product data with Gemini LLM",
    version="1.0.0"
)

# Enable CORS for cross-origin embedding on external sites
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # Allows any external website / localhost
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# -------------------------------------------------------------
# 2. Load PLM BOM Data Context
# -------------------------------------------------------------
engine = get_engine()
products_df = engine.db.get_products_df()

# Convert BOM into markdown context table for LLM grounding
context_data = products_df[['name', 'plm_id', 'revision', 'maturity', 'mass', 'material']].to_markdown()

SYSTEM_INSTRUCTION = f"""
You are an expert PLM AI Assistant helping an automotive engineer.
Here is the complete Bill of Materials (BOM) data for an electric motor:
{context_data}

Rules:
1. Answer the user's questions based ONLY on the data provided above.
2. You MUST explicitly cite the specific PLM ID (e.g., prd-12535825-...) for any component you mention to provide traceable evidence.
3. Be concise, precise, and professional.
"""

# -------------------------------------------------------------
# 3. Request / Response Schemas
# -------------------------------------------------------------
class ChatRequest(BaseModel):
    message: str
    api_key: Optional[str] = None


class ChatResponse(BaseModel):
    response: str
    status: str = "success"


# -------------------------------------------------------------
# 4. API Endpoints
# -------------------------------------------------------------
@app.get("/")
def root():
    return {
        "status": "online",
        "service": "PLM Intelligence API",
        "total_products": len(products_df),
        "endpoint": "/api/chat"
    }


@app.post("/api/chat", response_model=ChatResponse)
def chat_endpoint(payload: ChatRequest):
    user_query = payload.message.strip()
    if not user_query:
        raise HTTPException(status_code=400, detail="Message cannot be empty.")

    # Determine API key from request payload or environment variable
    effective_api_key = payload.api_key or os.environ.get("GEMINI_API_KEY")

    if not effective_api_key:
        raise HTTPException(
            status_code=400,
            detail="Gemini API Key is missing. Pass 'api_key' in the request JSON or set GEMINI_API_KEY environment variable."
        )

    try:
        genai.configure(api_key=effective_api_key)
        model = genai.GenerativeModel(
            model_name="gemini-1.5-flash",
            system_instruction=SYSTEM_INSTRUCTION
        )
        response = model.generate_content(user_query)
        reply_text = response.text if response and response.text else "No response generated by model."
        return ChatResponse(response=reply_text, status="success")

    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Gemini API Error: {str(e)}")


if __name__ == "__main__":
    import uvicorn
    uvicorn.run("api:app", host="0.0.0.0", port=8000, reload=True)
